"""`physical_validation` adapter: energy/kinetic/ensemble consistency diagnostics.

What this does
--------------
`physical_validation` (Motional, University of Amsterdam) checks whether a
trajectory is consistent with the ensemble it claims to sample: kinetic energy vs
the Maxwell–Boltzmann distribution, potential energy fluctuations vs the expected
heat capacity relation, and integrator step rejection.

The honest limits, stated before any number
-------------------------------------------
A diagnostic on a trajectory tells you whether *that run* looks consistent with
its target ensemble. It says nothing about whether the force field is physically
accurate, and a short run cannot establish a thermodynamic property. The checks
below are also only meaningful with enough decorrelated samples: the module's own
documentation asks for O(100) independent configurations, and a run shorter than
several correlation times will fail or pass for reasons unrelated to correctness.

So this adapter:
  * runs the real `physical_validation` API on a trajectory generated by this
    repository's own BAOAB Langevin integrator for a harmonic oscillator, where
    the exact answer is known, so a failure or pass can be interpreted;
  * reports the sample count and the correlation time, so the reader can judge
    whether the test had enough data;
  * does NOT run any protein or solvent trajectory.

Run:  python3 validation/adapters/physical_validation_check.py
"""

from __future__ import annotations

import json
import math
from typing import Any, Dict

N_SAMPLES = 20_000
DT = 0.01
GAMMA = 1.0
BETA = 2.0
OMEGA2 = 2.0   # U = 0.5 * OMEGA2 * x^2  -> exact var = 1/(beta*OMEGA2)


def _probe():
    try:
        import physical_validation as pv  # noqa: F401
        return True, None
    except Exception as exc:  # noqa: BLE001
        return False, f"{type(exc).__name__}: {exc}"


def generate_trajectory():
    """
    BAOAB Langevin on a 1-D harmonic oscillator, in the same operator splitting as
    `julia/src/Dynamics.jl::langevin_baoab_step!`.

    Returns positions, velocities, and the potential energies.
    """
    import numpy as np

    rng = np.random.default_rng(20240101)
    m = 1.0
    k = OMEGA2            # U = 0.5*k*x^2
    x = 1.0
    p = 0.0
    c1 = math.exp(-GAMMA * DT)
    c2 = math.sqrt((1.0 - c1 * c1) / BETA)
    xs = np.empty(N_SAMPLES)
    ps = np.empty(N_SAMPLES)
    us = np.empty(N_SAMPLES)
    force = lambda xx: -k * xx
    for i in range(N_SAMPLES):
        p += 0.5 * DT * force(x)
        x += 0.5 * DT * p / m
        p = c1 * p + c2 * math.sqrt(m) * rng.standard_normal()
        x += 0.5 * DT * p / m
        p += 0.5 * DT * force(x)
        xs[i] = x
        ps[i] = p
        us[i] = 0.5 * k * x * x
    return xs, ps, us


def autocorr_time(xs) -> float:
    import numpy as np
    n = len(xs)
    x = xs - xs.mean()
    v = np.dot(x, x) / n
    if v <= 0:
        return 1.0
    tau = 1.0
    for t in range(1, min(n - 1, 10 * max(1, n // 100))):
        c = np.dot(x[:-t], x[t:]) / (n * v)
        if c <= 0:
            break
        tau += 2.0 * c
    return tau


def run_checks() -> Dict[str, Any]:
    import numpy as np
    import physical_validation as pv

    xs, ps, us = generate_trajectory()
    tau = autocorr_time(xs)
    n_eff = len(xs) / tau
    var_exact = 1.0 / (BETA * OMEGA2)
    out: Dict[str, Any] = {
        "n_samples": int(len(xs)),
        "integrated_autocorrelation_time": float(tau),
        "effective_sample_size": float(n_eff),
        "position_variance_empirical": float(np.var(xs)),
        "position_variance_exact": float(var_exact),
        "variance_relative_error": float(abs(np.var(xs) - var_exact) / var_exact),
        "physical_validation_api": [],
    }

    # Try the real kinetic-energy distribution check. The API has changed across
    # versions, so we probe for the entry points rather than assuming one.
    candidates = ["kinetic_energy", "check_kinetic_energy", "ensemble"]
    out["physical_validation_api"] = [c for c in candidates if hasattr(pv, c)]

    results = {}
    # 1. Maxwell-Boltzmann check on the momenta, done two ways: through the
    #    package if the entry point exists, and directly otherwise. Reporting both
    #    keeps the adapter useful even if the API differs.
    mb_pkg = None
    try:
        if hasattr(pv, "kinetic_energy") and hasattr(pv.kinetic_energy,
                                                    "maxwell_boltzmann"):
            freqs = np.array([OMEGA2 ** 0.5])
            mb_pkg = bool(pv.kinetic_energy.maxwell_boltzmann(
                kin=np.array([ps]), temperature=1.0 / BETA, prng=None))
    except Exception as exc:  # noqa: BLE001
        mb_pkg = f"error: {type(exc).__name__}: {exc}"
    results["maxwell_boltzmann_via_package"] = mb_pkg

    # direct moment check: for a 1-D oscillator at inverse temperature beta, the
    # velocity variance is 1/(beta*m).
    var_p_exact = 1.0 / (BETA * 1.0)
    var_p_obs = float(np.var(ps))
    se = math.sqrt(2.0 * var_p_exact**2 / max(n_eff, 1.0))
    results["momentum_variance"] = {
        "empirical": var_p_obs,
        "exact": var_p_exact,
        "relative_error": abs(var_p_obs - var_p_exact) / var_p_exact,
        "standard_error": se,
        "consistent_within_5se": abs(var_p_obs - var_p_exact) < 5 * se,
    }
    results["package_version"] = getattr(pv, "__version__", "unknown")
    out["checks"] = results
    return out


def main() -> int:
    ok, blocker = _probe()
    if not ok:
        print(json.dumps({"status": "BLOCKED", "blocker": blocker,
                          "note": "install with: pip install physical_validation"}, indent=2))
        return 0
    print("== physical_validation on this repository's BAOAB output ==")
    res = run_checks()
    print(json.dumps(res, indent=2))
    print()
    print("Interpretation:")
    print("  * the trajectory is 1-D harmonic, so the exact answer is known;")
    print("  * the effective sample size, not the raw count, is what the error bars use;")
    print("  * a static structure or a short protein run would NOT be interpretable this way.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
